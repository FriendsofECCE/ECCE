"""End-to-end cases: run a real code, assert what reaches the far end.

A case here stores an INPUT DECK, not captured output -- the opposite of
tests/parsers, and the whole point.  The output is regenerated by the
code on every run, so a code upgrade that changes its wording fails an
assertion here instead of silently producing a missing property months
later.  That is the shape of #80 (Gaussian 16 dropped "atomic" from
"Mulliken atomic charges" and the property was never extracted again,
with no error anywhere).

Assertions are deliberately loose about exact numbers and strict about
structure.  Pinning an energy to ten digits would make this suite fail
on a code upgrade for a reason nobody needs to care about; pinning that
ORBENG has the same length as ORBOCC catches the bug class that actually
bites (see MoPanel::fillTable(), which reverses those vectors
independently and indexes both by the same row).
"""

import os

from pipeline import sect

HERE = os.path.dirname(os.path.abspath(__file__))


def expect_mopac_ch4(props, report):
    """CH4, PM7, VECTORS ALLVEC -- the whole MO chain in one job."""
    orbeng = props.get('ORBENG', [])
    orbocc = props.get('ORBOCC', [])
    orbsym = props.get('ORBSYM', [])
    mo = props.get('MO', [])

    report.check(bool(orbeng), 'ORBENG extracted')
    report.check(bool(orbocc), 'ORBOCC extracted')
    report.check(bool(orbsym), 'ORBSYM extracted')
    report.check(bool(mo), 'MO coefficients extracted')
    if not (orbeng and orbocc and mo):
        return

    n_eng = len(sect(orbeng[-1], 'values').split())
    n_occ = len(sect(orbocc[-1], 'values').split())
    n_sym = len(sect(orbsym[-1], 'values').split()) if orbsym else 0

    #  CH4 in MOPAC's minimal valence basis: C contributes s,px,py,pz and
    #  each H one s, so eight orbitals.  Hard-coded because it is a
    #  property of the molecule and the Hamiltonian, not of a captured
    #  file -- if this changes, something real changed.
    report.check(n_eng == 8, 'ORBENG has 8 orbitals (got %d)' % n_eng)

    #  THE INVARIANT THAT MATTERS.  MoPanel::fillTable() reverses the
    #  energy, occupancy and symmetry vectors independently and then
    #  indexes all three by the same row, so unequal lengths do not run
    #  out at the end -- a short occupancy vector reads past its end and
    #  a short symmetry vector mislabels every row.
    report.check(n_occ == n_eng,
                 'ORBOCC length matches ORBENG (%d vs %d)' % (n_occ, n_eng))
    report.check(n_sym == n_eng,
                 'ORBSYM length matches ORBENG (%d vs %d)' % (n_sym, n_eng))

    #  Eight valence electrons -> four doubly occupied orbitals.
    occ = [float(x) for x in sect(orbocc[-1], 'values').split()]
    report.check(abs(sum(occ) - 8.0) < 1e-6,
                 'occupancies sum to 8 electrons (got %g)' % sum(occ))
    report.check(occ[:4] == [2.0] * 4 and occ[4:] == [0.0] * 4,
                 'four filled levels then virtuals')

    #  THE GRAPHF FILE MUST BE THE SOURCE, not the printed eigenvector
    #  block.  Both parse types emit these keys and the File= one is
    #  delivered last, so it wins -- but only if MOPAC actually wrote it
    #  and mopac.desc's File= name matched, neither of which is visible
    #  from the values alone.
    #
    #  The tell is precision: mopac.mo prints six decimals because that
    #  is all the printed block has, mopac.mgf prints eight because the
    #  GRAPHF file carries Fortran doubles.  A value that stops at six
    #  means the fallback ran and the better source was missed.
    decimals = max(len(t.split('.')[1]) for t in
                   sect(orbeng[-1], 'values').split() if '.' in t)
    report.check(decimals >= 8,
                 'ORBENG came from the GRAPHF file, not the printed block '
                 '(%d decimals; 6 means the fallback ran)' % decimals)

    #  Energies must be in Hartree, not the eV MOPAC prints.  MoPanel
    #  hard-codes its column label to "Energy Hartree", so a missing
    #  conversion shows numbers 27x too large with no error at all.
    eng = [float(x) for x in sect(orbeng[-1], 'values').split()]
    report.check(sect(orbeng[-1], 'units') == 'Hartree',
                 'ORBENG units are Hartree (got %r)'
                 % sect(orbeng[-1], 'units'))
    report.check(-5.0 < eng[0] < 0.0,
                 'lowest orbital energy is a plausible Hartree value '
                 '(got %g; ~-0.92 expected, ~-25 would mean eV)' % eng[0])

    #  The MO table must be square in this basis and complete.  A short
    #  table is rejected by PropTable on load with "input vector length
    #  does not match rows*columns", which presents as the Orbitals panel
    #  simply refusing to compute (#108).
    size = (sect(mo[-1], 'size') or '')
    report.check(size.split() == ['8', '8'],
                 'MO table is 8x8 (got %r)' % size)
    n_vals = len(sect(mo[-1], 'values').split())
    report.check(n_vals == 64,
                 'MO table has rows*columns values (got %d, want 64)' % n_vals)

    #  The coefficients must have been brought out of MOPAC's own
    #  orthonormalised (Lowdin) basis into the AO basis, or the renderer
    #  draws the wrong shape while still looking like an orbital.  The
    #  tell is exact: in the Lowdin basis every orbital has sum(c^2)
    #  identically 1, and in the AO basis it does not.
    rows = [r.split() for r in sect(mo[-1], 'values').strip().splitlines()]
    sums = [sum(float(c)**2 for c in r) for r in rows if r]
    untransformed = [s for s in sums if abs(s - 1.0) < 1e-6]
    report.check(not untransformed,
                 'MO coefficients are in the AO basis, not MOPAC\'s Lowdin '
                 'basis (%d of %d orbitals still have sum(c^2)=1)'
                 % (len(untransformed), len(sums)))

    #  The Slater exponents, without which there is no basis to evaluate
    #  those coefficients against and nothing can be rendered at all.
    slater = props.get('SLATERBASIS')
    report.check(bool(slater), 'SLATERBASIS extracted')
    if slater:
        size = (sect(slater[-1], 'size') or '').split()
        report.check(size == ['5', '4'],
                     'SLATERBASIS is one row per atom, 4 columns (got %r)'
                     % ' '.join(size))
        vals = sect(slater[-1], 'values').split()
        #  Carbon first, then four hydrogens; a hydrogen has no p shell.
        report.check(vals[:1] == ['6'],
                     'SLATERBASIS names carbon first (got %r)' % vals[:1])
        report.check(float(vals[3]) == 0.0,
                     'carbon has no d exponent in PM7 (got %s)' % vals[3])


def expect_mopac_ch4_thermo(props, report):
    """CH4, PM7 FORCE THERMO -- thermochemistry into the Energies panel."""
    for key in ('ENTHALPY', 'ETHERM', 'ENTROPY', 'HEATCAP', 'THERMOTEMP',
                'EZEROPT'):
        report.check(bool(props.get(key)), '%s extracted' % key)
    if not all(props.get(k) for k in ('ENTHALPY', 'ETHERM', 'THERMOTEMP')):
        return

    temp = float(sect(props['THERMOTEMP'][-1], 'values'))
    #  MOPAC prints 298 K FIRST and then scans upward from 200 K, so any
    #  "take the last stanza" reading reports the top of the scan as room
    #  temperature -- plausible numbers, wrong temperature, no error.
    report.check(abs(temp - 298.0) < 1.0,
                 'thermochemistry is at 298 K (got %g)' % temp)

    h = float(sect(props['ENTHALPY'][-1], 'values'))
    u = float(sect(props['ETHERM'][-1], 'values'))
    #  H = U + RT, the relation ORCA states explicitly and MOPAC's own
    #  E_SCF equation implies.  This is what keeps ETHERM from being
    #  "corrected" back to the table's ENTHALPY column, which is a
    #  zero-point-free correction rather than a total.
    rt = (1.987204259 * temp / 1000.0) / 627.5094740631
    report.check(abs((h - u) - rt) < 1e-9,
                 'ENTHALPY - ETHERM equals RT (got %.10f, want %.10f)'
                 % (h - u, rt))

    #  Zero-point energy must still be its own property.  It is inside
    #  ENTHALPY and ETHERM (MOPAC's heat of formation contains it), and
    #  also reported separately, as for every other code.
    zpe = float(sect(props['EZEROPT'][-1], 'values'))
    report.check(zpe > 0.0, 'EZEROPT is positive (got %g)' % zpe)


def expect_nwchem_h2o(props, report):
    """Water, B3LYP/6-31G* -- and the regression guard for #126.

    NWChem does NOT write its properties to stdout.  nwchem.desc matches
    a separate machine-tagged trace file that NWChem writes itself, via
    its built-in `ecce_print <file>` directive -- so the deck carries
    that line and the monitor is pointed at the trace, not the .out.
    Auditing nwchem.desc against plain NWChem stdout instead wrongly
    concludes the whole file is dead.
    """
    for key in ('TE', 'ORBENG', 'ORBOCC', 'MO', 'GEOMTRACE', 'DIPOLE'):
        report.check(bool(props.get(key)), '%s extracted' % key)

    #  THE #126 GUARD.  nwchem.symlab writes $key/parseSym and
    #  nwchem.molab reads it, exiting 0 without a word when it is
    #  missing.  The monitor used to flush buffered blocks in Perl hash
    #  order, randomized per process, so which ran first was a coin flip
    #  -- roughly three runs in eight produced no symmetries at all,
    #  from the same output file, with no error.  It now flushes in
    #  descriptor-file order and nwchem.desc puts [SYMLAB] ahead of
    #  [MOLAB1..5].
    #
    #  This assertion is why the case exists.  If it starts failing
    #  intermittently, the ordering guarantee has been lost again.
    report.check(bool(props.get('ORBSYM')),
                 'ORBSYM extracted (#126: needs SYMLAB flushed before '
                 'MOLAB, which is descriptor-file order)')
    if not (props.get('ORBENG') and props.get('ORBSYM')):
        return

    n_eng = len(sect(props['ORBENG'][-1], 'values').split())
    n_sym = len(sect(props['ORBSYM'][-1], 'values').split())
    report.check(n_sym == n_eng,
                 'ORBSYM length matches ORBENG (%d vs %d)' % (n_sym, n_eng))

    #  The deck says noautosym, so every orbital is in the trivial
    #  irrep.  A run that produced anything else would mean the label
    #  table and the integer indices had come apart.
    syms = set(sect(props['ORBSYM'][-1], 'values').split())
    report.check(syms == {'a'},
                 'C1 geometry gives all-"a" symmetries (got %s)'
                 % sorted(syms))

    #  Water/6-31G* is 19 basis functions; B3LYP total energy is around
    #  -76.4 Hartree.  Loose on purpose -- the point is that a real
    #  number in the right region arrived, not that it matches to ten
    #  digits across NWChem releases.
    te = float(sect(props['TE'][-1], 'values'))
    report.check(-77.0 < te < -76.0,
                 'total energy is a plausible B3LYP/6-31G* value for water '
                 '(got %g)' % te)


#  H2, O2 (triplet) and CO -- the class exercise this trio exists for
#  (#199): "build a diatomic with NWChem, look at the shape of its MOs".
#  The three decks are ai.nwchem's own real output for a student's
#  default clicks (SCF/RHF or, for O2's open shell, SCF/UHF; Energy;
#  6-31G*) -- see check_nwchem_generation.py, which re-derives them from
#  the real generator on every run and fails first if it ever stops
#  reproducing what is checked in here.  This file's own job is the
#  other half: that a real NWChem run on that deck still gives a real
#  MoPanel something to draw.
def _check_mo_block(props, report, nOrbitals, engKey='ORBENG',
                    occKey='ORBOCC', moKey='MO', label=''):
    """The invariant MoPanel::fillTable() depends on, shared by all three
    (and both spins of O2): energies, occupations and the MO table must
    all agree on how many orbitals there are, or the table silently
    misindexes past the shorter vector."""
    eng = props.get(engKey, [])
    occ = props.get(occKey, [])
    mo = props.get(moKey, [])
    report.check(bool(eng), '%s extracted' % engKey)
    report.check(bool(occ), '%s extracted' % occKey)
    report.check(bool(mo), '%s coefficients extracted' % moKey)
    if not (eng and occ and mo):
        return None

    nEng = len(sect(eng[-1], 'values').split())
    nOcc = len(sect(occ[-1], 'values').split())
    report.check(nEng == nOrbitals,
                 '%s%s has %d orbitals (got %d)'
                 % (label, engKey, nOrbitals, nEng))
    report.check(nOcc == nEng,
                 '%s%s length matches %s (%d vs %d)'
                 % (label, occKey, engKey, nOcc, nEng))
    size = (sect(mo[-1], 'size') or '').split()
    report.check(size == [str(nOrbitals)] * 2,
                 '%s%s table is %dx%d (got %r)'
                 % (label, moKey, nOrbitals, nOrbitals, size))
    return [float(x) for x in sect(occ[-1], 'values').split()]


def expect_nwchem_h2_mos(props, report):
    """H2, RHF/6-31G* -- the simplest possible MO case: one filled sigma_g,
    the rest empty (sigma_u* first among them).  6-31G* adds no
    polarization function on hydrogen, so it is plain 6-31G there: 2
    functions per H, 4 for the molecule."""
    for key in ('TE', 'GEOMTRACE'):
        report.check(bool(props.get(key)), '%s extracted' % key)

    occ = _check_mo_block(props, report, 4)
    if occ is not None:
        report.check(occ == [2.0, 0.0, 0.0, 0.0],
                     'one filled sigma_g, the rest empty (got %s)' % occ)

    if props.get('TE'):
        te = float(sect(props['TE'][-1], 'values'))
        #  RHF/6-31G*: -1.13ish Hartree.  Loose window -- see the water
        #  case's own comment on why these are not pinned tighter.
        report.check(-1.20 < te < -1.05,
                     'total energy is a plausible RHF/6-31G* value for H2 '
                     '(got %g)' % te)


def expect_nwchem_co_mos(props, report):
    """CO, RHF/6-31G* -- a heteronuclear case with real orbital character
    (5sigma HOMO, mostly on C), 6-31G*/C+O is 28 functions."""
    for key in ('TE', 'GEOMTRACE'):
        report.check(bool(props.get(key)), '%s extracted' % key)

    occ = _check_mo_block(props, report, 28)
    if occ is not None:
        report.check(sum(occ) == 14.0,
                     'occupancies sum to 14 electrons (got %g)' % sum(occ))
        report.check(occ[:7] == [2.0] * 7 and occ[7:] == [0.0] * 21,
                     'seven filled levels then virtuals (got first 8: %s)'
                     % occ[:8])

    if props.get('TE'):
        te = float(sect(props['TE'][-1], 'values'))
        report.check(-113.0 < te < -112.0,
                     'total energy is a plausible RHF/6-31G* value for CO '
                     '(got %g)' % te)


def expect_nwchem_co_opt_mos(props, report):
    """CO, RHF/6-31G*, Geometry (optimisation) starting well off
    equilibrium (1.375 A) -- the regression guard for the "optimise then
    show orbitals" bug: NWChem's ecce_print of the MO vectors block is a
    one-shot per process (fires once, for the FIRST SCF evaluation of
    the whole optimisation) and a bare trailing task cannot retrigger
    it, so without ai.nwchem's fix ORBENG comes from the unconverged
    starting geometry instead of the converged one.

    Also the property-length invariant from the fix itself: the
    trailing "task scf gradient" ai.nwchem now appends must advance
    TEVEC and GEOMTRACE together, never leaving TEVEC one point ahead
    (GeomTracePropertyPanel indexes GEOMTRACE by TEVEC's row and a
    stray extra point reads past the last frame -- the MOPAC #86
    GEOMTRACE/TEVEC lesson in CLAUDE.md, here for NWChem's own
    Geometry+energy interaction instead of a code difference).
    """
    for key in ('TE', 'TEVEC', 'GEOMTRACE'):
        report.check(bool(props.get(key)), '%s extracted' % key)
    if not (props.get('TEVEC') and props.get('GEOMTRACE')):
        return

    report.check(len(props['TEVEC']) <= len(props['GEOMTRACE']),
                 'len(TEVEC) <= len(GEOMTRACE) (got %d vs %d)'
                 % (len(props['TEVEC']), len(props['GEOMTRACE'])))

    occ = _check_mo_block(props, report, 28)
    if occ is not None:
        report.check(sum(occ) == 14.0,
                     'occupancies sum to 14 electrons (got %g)' % sum(occ))
        report.check(occ[:7] == [2.0] * 7 and occ[7:] == [0.0] * 21,
                     'seven filled levels then virtuals (got first 8: %s)'
                     % occ[:8])

    if props.get('ORBENG'):
        #  Orbital 7 (0-based index 6): -0.5474 at the 1.375 A starting
        #  geometry, -0.5457 at the converged one (~1.126 A) -- a real
        #  but modest shift, so the window is narrow and placed to
        #  reject the unconverged value rather than merely accept a
        #  plausible one.
        eng = [float(x) for x in
              sect(props['ORBENG'][-1], 'values').split()]
        report.check(-0.5465 < eng[6] < -0.5450,
                     'orbital 7 is at the CONVERGED geometry, not the '
                     'first optimisation step (got %.6f, first-step '
                     'value is -0.5474)' % eng[6])

    if props.get('TE'):
        te = float(sect(props['TE'][-1], 'values'))
        #  Converged RHF/6-31G* energy for CO near its equilibrium bond
        #  length; the 1.375 A starting point is -112.627, well outside
        #  this window, so this also catches a TE that never advanced
        #  past the first step.
        report.check(-112.74 < te < -112.73,
                     'total energy is the CONVERGED RHF/6-31G* value for '
                     'CO (got %g)' % te)


def expect_nwchem_o2_triplet_mos(props, report):
    """O2, UHF/6-31G*, multiplicity 3 -- the one that actually matters:
    open shell, separate alpha and beta orbital sets.  16 electrons split
    9 alpha / 7 beta (S=1, a triplet); the alpha HOMO is the degenerate
    pi*g pair O2 is famous for having half-filled.  6-31G*/O2 is 28
    functions per spin.
    """
    for key in ('TE', 'GEOMTRACE', 'S2'):
        report.check(bool(props.get(key)), '%s extracted' % key)

    occA = _check_mo_block(props, report, 28, label='alpha ')
    occB = _check_mo_block(props, report, 28, engKey='ORBENGBETA',
                           occKey='ORBOCCBETA', moKey='MOBETA',
                           label='beta ')
    if occA is not None and occB is not None:
        nAlpha = sum(1 for o in occA if o > 0)
        nBeta = sum(1 for o in occB if o > 0)
        report.check(nAlpha == 9,
                     '9 alpha orbitals occupied (got %d)' % nAlpha)
        report.check(nBeta == 7,
                     '7 beta orbitals occupied (got %d)' % nBeta)
        report.check(nAlpha + nBeta == 16,
                     'alpha+beta occupied = 16 electrons (got %d)'
                     % (nAlpha + nBeta))

        #  The alpha HOMO (index 8, 0-based) must be part of a degenerate
        #  pair with orbital 7 -- the two components of pi*g.  A UHF run
        #  that broke that symmetry (wrong geometry, wrong basis order)
        #  would still have 9 occupied alpha orbitals but not this.
        engA = [float(x) for x in
               sect(props['ORBENG'][-1], 'values').split()]
        report.check(abs(engA[7] - engA[8]) < 1e-4,
                     'alpha HOMO is part of a degenerate pair (orbitals 7 '
                     'and 8: %.6f, %.6f)' % (engA[7], engA[8]))

    if props.get('TE'):
        te = float(sect(props['TE'][-1], 'values'))
        #  UHF/6-31G* triplet O2: -149.6ish Hartree.
        report.check(-150.0 < te < -149.0,
                     'total energy is a plausible UHF/6-31G* value for O2 '
                     '(got %g)' % te)


def expect_qe_si(props, report):
    """Bulk silicon, PBE, 2 atoms -- QE's scalar and tensor results.

    Quantum ESPRESSO is a plane-wave code: no basis set, no orbitals in
    ECCE's sense.  What it does have that no other code here does is a
    STRESS tensor, and that is worth guarding because the value carries
    its units in the section HEADER rather than beside the numbers --
    the shape that silently produced wrong values rather than none when
    QE was first integrated.
    """
    for key in ('TE', 'STRESS', 'PRESSURE', 'VERSION'):
        report.check(bool(props.get(key)), '%s extracted' % key)
    if not (props.get('TE') and props.get('STRESS')):
        return

    te = float(sect(props['TE'][-1], 'values'))
    #  Two silicon atoms with this pseudopotential land near -11.3
    #  Hartree.  QE prints Ry, so a value near -22.6 would mean the
    #  conversion was dropped -- the range is chosen to tell those apart
    #  rather than to pin the number.
    report.check(-15.0 < te < -8.0,
                 'total energy is a plausible Hartree value for Si2 '
                 '(got %g; ~-22.6 would mean Ry went unconverted)' % te)

    stress = sect(props['STRESS'][-1], 'values').split()
    report.check(len(stress) == 9,
                 'STRESS is a full 3x3 tensor (got %d values)' % len(stress))
    if len(stress) == 9:
        #  A stress tensor is symmetric.  This is a real check on the
        #  parse: a row/column transposition or a dropped element shows
        #  up here and nowhere else.
        s = [float(x) for x in stress]
        sym = (abs(s[1] - s[3]) < 1e-6 and abs(s[2] - s[6]) < 1e-6
               and abs(s[5] - s[7]) < 1e-6)
        report.check(sym, 'STRESS tensor is symmetric (got %s)' % stress)


def expect_gromacs_water(props, report):
    """216 SPC waters, 50 steps of MD.

    The point of this case is the WRAPPED ENERGY BLOCK.  With enough
    terms GROMACS splits its "Energies (kJ/mol)" table over two rows:

        LJ (SR)   Coulomb (SR)    Potential   Kinetic En.  Total Energy
        2.13e+03  -1.21e+04      -9.97e+03    2.31e+03     -7.66e+03
      Conserved En.  Temperature  Pressure (bar)
       -7.32e+03     4.31e+02     2.36e+03

    so TE comes from the first row and PRESSURE from the second.  A
    parser that reads only the first row silently reports a plausible
    number for the wrong quantity -- CLAUDE.md records this shape as
    producing wrong values rather than none.  A short minimisation does
    not wrap, so the .mdp here deliberately runs MD with temperature
    coupling to make it.

    It also guards the averages suppression: GROMACS prints one last
    "Energies (kJ/mol)" block under "A V E R A G E S", and [NULL] exists
    to stop that being taken as the final step's result.
    """
    for key in ('TE', 'PRESSURE'):
        report.check(bool(props.get(key)), '%s extracted' % key)
    if not (props.get('TE') and props.get('PRESSURE')):
        return

    te = float(sect(props['TE'][-1], 'values'))
    pressure = float(sect(props['PRESSURE'][-1], 'values'))

    #  TE is the Total Energy of 216 waters, a few thousand kJ/mol
    #  negative.  Loose, because it depends on the random starting
    #  velocities; what must not happen is picking up the Potential
    #  (~-1e4) or the Conserved En. from the wrong column.
    report.check(-9.5e3 < te < -5.0e3,
                 'TE is the Total Energy, not the Potential '
                 '(got %g; ~-1.0e4 would be the Potential)' % te)

    #  Pressure lives in the SECOND row.  Reading it from the first
    #  would pick up a kJ/mol energy of order 1e3-1e4 with the wrong
    #  sign pattern; a real pressure here is a few thousand bar.
    report.check(abs(pressure) < 2.0e4,
                 'PRESSURE came from the wrapped second row (got %g)'
                 % pressure)

    #  The averages block is the LAST "Energies (kJ/mol)" in the file.
    #  If [NULL] stopped suppressing it, TE would be the average rather
    #  than the final step, and the two differ by enough to see.
    report.check(len(props.get('TEVEC', [])) >= 2,
                 'TEVEC accumulated per-step energies (got %d)'
                 % len(props.get('TEVEC', [])))


