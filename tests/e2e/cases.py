#  How to find and invoke each code.  A code that is absent is SKIPPED
#  with its name reported, never silently passed -- an e2e suite that
#  quietly tests nothing is worse than no e2e suite.
CODES = {
    'nwchem': dict(
        binary='nwchem',
        #  Debian's nwchem-openmpi ships /usr/bin/nwchem AND
        #  /usr/bin/nwchem.openmpi; other images ship only the
        #  variant-suffixed name, which is how this silently skipped in
        #  CI while the apt step reported success.
        search=('/usr/bin/nwchem', '/usr/bin/nwchem.openmpi',
                '/usr/bin/nwchem.mpich'),
        argv=lambda exe, deck: [exe, deck],
        packaged='nwchem-openmpi (or nwchem)',
    ),
    'mopac': dict(
        binary='mopac',
        search=(),
        argv=lambda exe, deck: [exe, deck],
        #  MOPAC derives its output name by stripping the input's
        #  extension, so the deck name determines the output name.
        packaged='mopac',
    ),
}
