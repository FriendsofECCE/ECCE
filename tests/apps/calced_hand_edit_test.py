#!/usr/bin/env python3
"""
An input file edited by hand is not silently regenerated by Save (#622).

ECCE records a fingerprint of the deck it writes; a Save that would
regenerate a deck that no longer matches asks.  ECCE_CALCED_HANDEDIT=
keep|regenerate answers for a headless run.  Three runs on one ORCA
calculation: Save generates (no question); after a hand edit Save with
"keep" leaves the file alone; Save with "regenerate" rewrites it.

Same installed tree, isolation and services as run_tests.py.  Exit 77 (skip)
without an install or Xvfb.
"""

import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

import fixture    # noqa: E402
import run_tests  # noqa: E402
import symmetry_find_test as sym  # noqa: E402
import calced_constraints_line_test as cl  # noqa: E402

MARK = "# EDITED BY HAND\n"


def deck(calc):
    inputs = os.path.join(calc, "Inputs")
    names = sorted(f for f in os.listdir(inputs) if f.endswith(".orcain")) \
        if os.path.isdir(inputs) else []
    return os.path.join(inputs, names[0]) if names else None


def main():
    def checkApp(display, name, results, verbose=False):
        folder = os.path.join(fixture.stateDir(), "handedit-localdata")
        shutil.rmtree(folder, ignore_errors=True)
        project = os.path.join(folder, "users", "local", "p")
        os.makedirs(project)
        shutil.copy(cl.PROJECT_META, os.path.join(project, ".ecce-meta"))
        os.environ["ECCE_LOCAL_DATA"] = folder
        restorePrefs = fixture.settleUpgradeNotices()
        try:
            calc = cl.makeCalc(project, "hand", os.path.join(cl.FIX, "calc-orca-water-ccpvdz"))
            os.makedirs(os.path.join(calc, "Inputs"), exist_ok=True)
            url = "file://" + calc + "/"

            def save(runtype, answer):
                os.environ["ECCE_CALCED_HANDEDIT"] = answer
                try:
                    return sym.scripted(display, "calced", "ECCE_CALCED_SCRIPT",
                                        ["wait 9000", "runtype " + runtype, "wait 3000",
                                         "button save", "wait 6000", "quit"], url)
                finally:
                    os.environ.pop("ECCE_CALCED_HANDEDIT", None)

            def read():
                path = deck(calc)
                return open(path, errors="replace").read() if path else None

            log = save("Energy", "cancel")
            first = read()
            sym.check(first is not None and MARK not in first,
                      "the first Save generates a deck", run_tests._tail(log, 30))
            print("Inputs:", sorted(os.listdir(os.path.join(calc, "Inputs"))))

            log = save("Geometry", "cancel")      # untouched deck: no question
            sym.check(read() is not None and "ECCE_CALCED_HANDEDIT" not in log,
                      "an untouched deck is regenerated without a question",
                      run_tests._tail(log, 30))

            edited = read() + MARK
            with open(deck(calc), "w") as h:
                h.write(edited)

            log = save("Energy", "keep")
            sym.check(read() == edited, "Keep my input leaves the edited deck alone",
                      run_tests._tail(log, 30))

            log = save("Geometry", "regenerate")
            now = read()
            sym.check(now is not None and MARK not in now,
                      "Regenerate rewrites the deck", run_tests._tail(log, 30))
        finally:
            restorePrefs()
            os.environ.pop("ECCE_LOCAL_DATA", None)
        if sym.failures:
            results.fail("calced-hand-edit", "%d wrong: %s"
                         % (len(sym.failures), "; ".join(sym.failures)))
    run_tests.checkApp = checkApp
    sys.argv = [sys.argv[0], "--app", "calced"] + sys.argv[1:]
    return run_tests.main()


if __name__ == "__main__":
    sys.exit(main())
