def wrmolcas(bs):
    out = sys.stdout.write
    gbs = dict(bs['gbs'])
    gbs.pop('coordinants', None)
    gbs.pop('polarization', None)
    for atom in sorted(gbs):
        orbitals = gbs[atom]
        name = ELEMENT_NAMES.get(atom, '').upper()
        out('* %s\n Basis set\n %-12s/ inline\n' % (name, name))
        highest = 0
        for index, shell in enumerate('SPDFGH'):
            if any(shell in orbital_type for orbital_type, rows in orbitals):
                highest = index
        out('        %3d.   %d\n' % (ELEMENT_NUMBERS.get(atom, 0), highest))
        for shell in 'SPDFGH':
            matching = [(orbital_type, rows) for orbital_type, rows in orbitals
                        if shell in orbital_type]
            if not matching:
                continue
            row_count = sum(len(rows) for orbital_type, rows in matching)
            total_coeff = sum(1 if orbital_type == 'SP' else
                              (len(rows[0]) - 1 if rows else 0)
                              for orbital_type, rows in matching)
            out('* %s-type functions\n%5d%5d\n' % (shell, row_count, total_coeff))
            for orbital_type, rows in matching:
                for row in rows:
                    out('%17.8f\n' % perl_number(row[0]))
            column = 0
            for orbital_type, rows in matching:
                coefficients = []
                for row in rows:
                    coefficients = row[1:]
                    index = 0
                    while index < total_coeff:
                        if index == column and orbital_type == 'SP' and shell in 'SP':
                            c = 0 if shell == 'S' else 1
                            out('%12s' % (coefficients[c] if c < len(coefficients) else ''))
                        elif index == column:
                            for coefficient in coefficients:
                                out('%12s' % coefficient)
                            index += len(coefficients) - 1
                        else:
                            out('%12.8f' % 0)
                        index += 1
                    out('\n')
                # The final row, rather than the declared width, advances the column.
                if orbital_type != 'SP':
                    column += len(coefficients) - 1
                column += 1
    out('$END\n')
