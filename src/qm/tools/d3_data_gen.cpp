// Build-time converter: reads the array literals of the unchanged simple-dftd3
// and mctc-lib data files (third_party/simple-dftd3-data) and writes them as a
// C++ table for d3.cpp.  Only the numbers are taken; every array length is
// checked so a changed upstream layout fails the build instead of shifting data.
//
//   d3_data_gen reference.f90 r4r2.f90 covrad.f90 out.inc
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

namespace {

[[noreturn]] void die(const std::string& m) {
  std::cerr << "d3_data_gen: " << m << "\n";
  std::exit(1);
}

// The file with every Fortran comment ('!' to end of line) removed.
std::string load(const std::string& path) {
  std::ifstream f(path);
  if (!f) die("cannot read " + path);
  std::string out, line;
  while (std::getline(f, line)) {
    const auto bang = line.find('!');
    out += (bang == std::string::npos ? line : line.substr(0, bang));
    out += '\n';
  }
  return out;
}

// The numbers of the "[ ... ]" literal that starts after text[pos].
std::vector<double> numbers_after(const std::string& t, size_t pos, size_t* end = nullptr) {
  const size_t a = t.find('[', pos);
  const size_t b = t.find(']', a);
  if (a == std::string::npos || b == std::string::npos) die("no array literal");
  std::vector<double> v;
  const char* p = t.c_str() + a + 1;
  const char* e = t.c_str() + b;
  while (p < e) {
    if ((*p >= '0' && *p <= '9') || *p == '-' || *p == '+' || *p == '.') {
      char* q;
      const double x = std::strtod(p, &q);
      if (q == p) die("bad number");
      v.push_back(x);
      p = q;
      if (p + 3 <= e && std::string(p, 3) == "_wp") p += 3;
    } else {
      ++p;
    }
  }
  if (end) *end = b;
  return v;
}

std::vector<double> named(const std::string& t, const std::string& anchor, size_t n) {
  const size_t pos = t.find(anchor);
  if (pos == std::string::npos) die("'" + anchor + "' not found");
  auto v = numbers_after(t, pos + anchor.size());
  if (v.size() != n) die("'" + anchor + "' has " + std::to_string(v.size()) + " values, expected " + std::to_string(n));
  return v;
}

void put(std::ostream& o, const char* type, const char* name, const std::vector<double>& v) {
  o << "const " << type << " " << name << "[" << v.size() << "] = {";
  for (size_t i = 0; i < v.size(); ++i) {
    if (i % 8 == 0) o << "\n";
    char b[32];
    std::snprintf(b, sizeof b, "%.10g,", v[i]);
    o << b;
  }
  o << "};\n";
}

}  // namespace

int main(int argc, char** argv) {
  if (argc != 5) die("usage: d3_data_gen reference.f90 r4r2.f90 covrad.f90 out.inc");
  constexpr int max_elem = 103, max_ref = 7, max_elem_r = 118;
  constexpr size_t npair = max_elem * (max_elem + 1) / 2, nc6 = size_t(max_ref) * max_ref * npair;

  const std::string ref = load(argv[1]);
  const auto nref = named(ref, "number_of_references(max_elem) =", max_elem);
  const auto refcn = named(ref, "reference_cn(max_ref, max_elem) =", max_ref * max_elem);

  // c6ab_view(a:b) = [ ... ] blocks fill the flat (Fortran-ordered) table.
  std::vector<double> c6(nc6, 0.0);
  std::vector<char> seen(nc6, 0);
  const std::string tag = "c6ab_view(";
  for (size_t pos = ref.find(tag); pos != std::string::npos; pos = ref.find(tag, pos)) {
    pos += tag.size();
    long lo = 0, hi = 0;
    if (std::sscanf(ref.c_str() + pos, "%ld:%ld)", &lo, &hi) != 2) continue;  // the pointer declaration
    const size_t eq = ref.find('=', pos);
    if (ref.compare(ref.find_first_not_of(" ", eq + 1), 1, "[") != 0) continue;  // "=> c6ab"
    size_t end;
    const auto v = numbers_after(ref, eq, &end);
    if (lo < 1 || hi < lo || size_t(hi) > nc6 || v.size() != size_t(hi - lo + 1)) die("bad c6ab_view block " + std::to_string(lo));
    for (size_t k = 0; k < v.size(); ++k) {
      c6[lo - 1 + k] = v[k];
      seen[lo - 1 + k] = 1;
    }
    pos = end;
  }
  for (size_t k = 0; k < nc6; ++k)
    if (!seen[k]) die("c6 entry " + std::to_string(k + 1) + " not set");

  const auto r4r2 = named(load(argv[2]), "r4_over_r2(max_elem) =", max_elem_r);
  const auto cov = named(load(argv[3]), "covalent_rad_2009(max_elem) = aatoau *", max_elem_r);

  std::ostringstream o;
  o << "// Generated by d3_data_gen from third_party/simple-dftd3-data; do not edit.\n"
    << "namespace qm { namespace d3data {\n"
    << "constexpr int max_elem = " << max_elem << ", max_ref = " << max_ref << ", max_elem_r = " << max_elem_r << ";\n";
  put(o, "int", "number_of_references", nref);
  put(o, "double", "reference_cn", refcn);
  put(o, "double", "reference_c6", c6);
  put(o, "double", "r4_over_r2", r4r2);
  put(o, "double", "covalent_rad_2009_angstrom", cov);
  o << "}}  // namespace qm::d3data\n";
  std::ofstream out(argv[4]);
  out << o.str();
  if (!out) die(std::string("cannot write ") + argv[4]);
  return 0;
}
