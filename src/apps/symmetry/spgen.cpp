// Return the original molecular group generators; the legacy Fortran code
// uses packed integer pointers into shared rotoinversion tables. This C++
// table stores the resolved matrices and keeps the same 46-name numbering.
bool generatorSetFor(const std::string& requested, std::vector<Matrix>& generators) {
  const auto& names = molecularGroups();
  const auto found = std::find(names.begin(), names.end(), requested);
  if (found == names.end()) return false;
  const std::size_t index = static_cast<std::size_t>(found - names.begin());
  generators = generatorTable()[index];
  return true;
}
